#[test]
fn the_wait_prefers_a_matching_acknowledgement_and_then_the_deadline() {
    let ack = Ack {
        nonce: NONCE.to_owned(),
    };
    let wait = instance::TAKEOVER_WAIT;
    let under = wait
        .checked_sub(Duration::from_nanos(1))
        .expect("the wait is longer than a nanosecond");
    let wrong = Ack {
        nonce: "f".repeat(instance::NONCE_LEN),
    };
    assert_eq!(
        instance::phase(Some(&ack), NONCE, Duration::ZERO),
        Phase::Acked
    );
    assert_eq!(instance::phase(Some(&ack), NONCE, wait), Phase::Acked);
    assert_eq!(instance::phase(None, NONCE, under), Phase::Waiting);
    assert_eq!(instance::phase(None, NONCE, wait), Phase::TimedOut);
    assert_eq!(instance::phase(Some(&wrong), NONCE, under), Phase::Waiting);
    assert_eq!(instance::phase(Some(&wrong), NONCE, wait), Phase::TimedOut);
}

fn judge(record: &Record, hold: Hold, live: Liveness, caller: &Caller) -> Verdict {
    instance::judge(record, hold, live, caller)
}

#[test]
fn a_free_record_is_reclaimed_when_the_pid_is_gone_or_reused_and_only_then() {
    let live_record = Record::Parsed(placed());
    let here = caller(Server::Name("ae".to_owned()), true, true);
    assert_eq!(
        judge(&Record::Absent, Hold::Free, Liveness::Gone, &here),
        Verdict::Reclaim,
        "no record"
    );
    assert_eq!(
        judge(&live_record, Hold::Free, Liveness::Gone, &here),
        Verdict::Reclaim,
        "pid gone"
    );
    assert_eq!(
        judge(&live_record, Hold::Free, Liveness::Reused, &here),
        Verdict::Reclaim,
        "start identity differs"
    );
    assert_eq!(
        judge(&Record::Damaged, Hold::Free, Liveness::Same, &here),
        Verdict::Reclaim,
        "an unlocked damaged file is not a live record"
    );
    assert_eq!(
        judge(&live_record, Hold::Free, Liveness::Same, &here),
        Verdict::Refuse(Doubt::LockNotHeld)
    );
    assert_eq!(
        judge(&live_record, Hold::Free, Liveness::Unknown, &here),
        Verdict::Refuse(Doubt::Unknown)
    );
}

#[test]
fn a_held_record_is_focused_only_on_the_same_ae_owned_server_and_never_reclaimed() {
    let live_record = Record::Parsed(placed());
    let same = caller(Server::Name("ae".to_owned()), true, true);
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Same, &same),
        Verdict::Focus {
            session: "lane".to_owned()
        }
    );
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Gone, &same),
        Verdict::Refuse(Doubt::NotHolder),
        "the lock is held, but the recorded pid is gone"
    );
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Reused, &same),
        Verdict::Refuse(Doubt::NotHolder),
        "the lock is held, but the start identity differs"
    );
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Unknown, &same),
        Verdict::Refuse(Doubt::Unknown),
        "a held lock with no readable start identity is doubt"
    );
    let elsewhere = caller(Server::Name("ae-dev".to_owned()), true, true);
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Same, &elsewhere),
        Verdict::TakeOver,
        "another server"
    );
    let outside = caller(Server::None, false, false);
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Same, &outside),
        Verdict::TakeOver,
        "not in tmux"
    );
    let user = caller(Server::Name("ae".to_owned()), true, false);
    assert_eq!(
        judge(&live_record, Hold::Held, Liveness::Same, &user),
        Verdict::TakeOver,
        "the same name on a server ae does not own"
    );
    let socket = Server::Socket("/tmp/tmux-1/ae".to_owned());
    let on_socket = Record::Parsed(Instance {
        server: socket.clone(),
        ..placed()
    });
    assert_eq!(
        judge(
            &on_socket,
            Hold::Held,
            Liveness::Same,
            &caller(socket, true, true)
        ),
        Verdict::Focus {
            session: "lane".to_owned()
        }
    );
    let ambient = Record::Parsed(Instance {
        server: Server::Ambient,
        ..placed()
    });
    assert_eq!(
        judge(
            &ambient,
            Hold::Held,
            Liveness::Same,
            &caller(Server::Ambient, true, true)
        ),
        Verdict::TakeOver,
        "the ambient server is not an ae-owned server"
    );
    let nowhere = Record::Parsed(Instance {
        server: Server::None,
        session: String::new(),
        window: String::new(),
        pane: String::new(),
        ..placed()
    });
    assert_eq!(
        judge(&nowhere, Hold::Held, Liveness::Same, &same),
        Verdict::TakeOver,
        "an app outside tmux cannot be focused"
    );
}

#[test]
fn doubt_never_steals_a_held_or_unreadable_record() {
    let here = caller(Server::Name("ae".to_owned()), true, true);
    for live in [
        Liveness::Gone,
        Liveness::Same,
        Liveness::Reused,
        Liveness::Unknown,
    ] {
        assert_eq!(
            judge(&Record::Damaged, Hold::Held, live, &here),
            Verdict::Refuse(Doubt::Unreadable),
            "{live:?}"
        );
        assert_eq!(
            judge(&Record::Absent, Hold::Held, live, &here),
            Verdict::Refuse(Doubt::Unreadable)
        );
        assert_eq!(
            judge(&Record::Parsed(placed()), Hold::Unreadable, live, &here),
            Verdict::Refuse(Doubt::Unreadable)
        );
        assert_eq!(
            judge(&Record::Damaged, Hold::Unreadable, live, &here),
            Verdict::Refuse(Doubt::Unreadable)
        );
    }
}

