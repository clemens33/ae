//! Frozen acceptance for one `ae app` per state root.
//!
//! Oracle: brief `.local/brief-appsingle.md`, lead ruling
//! `ae-20261124T135451Z-a5396a19` (option 1) and
//! `ae-20261124T135811Z-894d0356` (D2, D3, D4). This file is the contract.
//! `ca9789b0` is amended here: the focus line names an ignored home, and a
//! held lock whose pid is gone or whose start identity differs is doubt.
//! `ae::app::instance` is the app record. It is not `ae::instance`, which
//! selects the state root.
//!
//! RED on `48e477ed`: the module is absent, so this suite does not compile.
//! The bytes below are the grammar. A parse that succeeds is exactly those
//! bytes. Do not edit this file to match an implementation.
//!
//! Files, directly under the state root, beside `app-view`:
//! `app-instance.lock`, `app-instance`, `app-takeover`, `app-takeover-ack`.
//!
//! The running app holds `store::lock` with no wait on the sibling
//! `app-instance.lock` (the record file stays `app-instance`). `WouldBlock`
//! is [`Hold::Held`]. Any other lock error is [`Hold::Unreadable`]. A missing
//! file is [`Record::Absent`]. The request and the acknowledgement are
//! written with `store::publish_private` (temp, fsync, rename) and a symlink
//! at the path is refused, as `saved::write_file` refuses one.
//!
//! The live app polls the request on the existing `TICK` (100 ms). It does
//! not start a thread for the poll. It honours a request only when
//! [`targets_me`] is true, and then, in this order: `leave_the_view`, write
//! the acknowledgement, quit, and drop the lock last. The quit line is
//! [`took_over_line`] and nothing else (no exit hint), and the status is 0.
//! A request it does not honour is left in place. The requester removes the
//! request and the acknowledgement after a matching acknowledgement, and
//! removes the request on timeout. Timeout is [`TAKEOVER_WAIT`], status
//! [`ae::EXIT_UNAVAILABLE`], stderr [`timeout_line`], stdout empty. The
//! requester does not signal the recorded pid. One observation prefers a
//! matching acknowledgement over the deadline. After `phase` has returned
//! [`Phase::TimedOut`] the process is on the refuse path and does not accept
//! a later acknowledgement.
//!
//! Focus runs the `tmux::jump_client_command` shape through the existing
//! tmux `run` door: `switch-client -c <client> -t <session>`, then
//! `select-window -t <pane>` and `select-pane -t <pane>`, using the record's
//! session and pane. No new `Command`, and `tests/it/doors.rs` counts stay
//! (D4). The client name comes from a door that already exists; a missing
//! one stops for lead. The line is [`focused_line`]. A named home is not
//! applied, and the line says so (D3). Status 0, stdout empty, no TUI.
//!
//! The record stores the socket `doors::caller_server` observed, hex-encoded,
//! and the next caller compares that same socket. `Caller.ae_owned` is true
//! only for this instance's own server (`ae::instance::own_server`, or the
//! declared `AE_TMUX_SERVER` pair when that is the server this process
//! launches on). Any other tmux takes the take-over path.
//!
//! `--new` ([`NEW_FLAG`]) holds no lock and no record and never writes
//! `app-view`. It may restore that file once, as a fresh start does. It does
//! not combine with `--app-own` or `--app-view`.
//!
//! A pane that carries a non-empty `@ae_console` (a `chat = app` window,
//! including its respawn) neither holds nor consults the record (D2). An
//! empty or absent stamp is governed. A stamp tmux did not answer is doubt,
//! not an exemption. A fixture that needs a second TUI uses `--new` or a
//! pane that carries the stamp. This file does not forbid that move.
//!
//! Typed `ae app`, plain `ae` and `ae <name>` landings are governed. An
//! exec restart keeps the pid and the start identity, so [`restart`] treats
//! it as the same instance. When the record names that pid and that start
//! identity, the result is [`Restart::Governed`]: the process takes the lock
//! again and keeps the record. [`Restart::Fresh`], the `--new` effects,
//! applies only when [`Hold::Held`] and the record does not name this
//! process. The argv still cannot combine `--new` with `--app-view`.
//! `tests/it/app_hint_spec.rs` takes the frozen `USAGE` text.
//!
//! The grammar is the space-separated `1` lines below. The request carries
//! the target pid, the target start identity, the requester pid and the
//! nonce. It has no `from_start`, `at` or `until` field. [`TAKEOVER_WAIT`]
//! is 5 s. The plan's `i1|` / `t1|` / `a1|` lines and its 10 s wait are not
//! this contract.
//!
//! Doubt refuses with [`doubt_line`], status [`ae::EXIT_UNAVAILABLE`], stdout
//! empty, and does not replace a held or unproven record. A held lock whose
//! recorded pid is gone, or whose start identity differs, is
//! [`Doubt::NotHolder`], not a focus and not a reclaim. The embedded
//! orchestrator panel is this process. The `ae orchestrator` seat is out of
//! scope and holds no record.
//!
//! The fuzz target `app_instance` calls the three parsers. A value that
//! parses renders back to the same bytes.

