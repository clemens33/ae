fn socket_token(path: &str) -> String {
    use std::fmt::Write;
    let mut token = String::from("S:");
    for byte in path.as_bytes() {
        write!(token, "{byte:02x}").expect("hex");
    }
    token
}

#[test]
fn a_socket_path_is_lowercase_hex_and_round_trips_including_a_space() {
    for path in ["/tmp/ae.sock", "/tmp/ae sock", "/tmp/ä"] {
        let token = socket_token(path);
        let bytes = line(&["1", "4242", IDENT, &token, "lane", "@1", "%7"]);
        let parsed = instance::parse_instance(&bytes).expect(path);
        assert_eq!(parsed.server, Server::Socket(path.to_owned()));
        assert_eq!(
            instance::render_instance(&parsed).as_deref(),
            Some(bytes.as_slice()),
            "{path}"
        );
        assert!(bytes.ends_with(b"\n") && !bytes[..bytes.len() - 1].contains(&b'\n'));
    }
}

#[test]
fn the_longest_legal_record_fits_the_cap_and_one_byte_over_the_cap_does_not() {
    let ident = "a".repeat(instance::IDENTITY_MAX);
    let session = "b".repeat(128);
    let path = format!("/{}", "c".repeat(instance::SOCKET_MAX - 1));
    assert_eq!(path.len(), instance::SOCKET_MAX);
    let token = socket_token(&path);
    let bytes = line(&[
        "1",
        "4294967295",
        &ident,
        &token,
        &session,
        "@4294967295",
        "%4294967295",
    ]);
    assert!(bytes.len() <= instance::INSTANCE_CAP, "{}", bytes.len());
    let parsed = instance::parse_instance(&bytes).expect("the longest legal record");
    assert_eq!(parsed.pid, u32::MAX);
    assert_eq!(
        instance::render_instance(&parsed).as_deref(),
        Some(bytes.as_slice())
    );

    let mut over = bytes.clone();
    over.push(b'x');
    while over.len() <= instance::INSTANCE_CAP {
        over.push(b'x');
    }
    assert!(instance::parse_instance(&over).is_none(), "over the cap");
    assert!(instance::parse_instance(&[b'x'; instance::INSTANCE_CAP + 1]).is_none());
}

