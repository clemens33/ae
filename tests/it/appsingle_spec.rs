fn line(fields: &[&str]) -> Vec<u8> {
    let mut text = fields.join(" ");
    text.push('\n');
    text.into_bytes()
}

fn placed() -> Instance {
    let bytes = line(&["1", "4242", IDENT, "L:ae", "lane", "@1", "%7"]);
    let parsed = instance::parse_instance(&bytes).expect("a placed record parses");
    assert_eq!(
        instance::render_instance(&parsed).as_deref(),
        Some(bytes.as_slice()),
        "a placed record renders to the one spelling"
    );
    parsed
}

fn caller(server: Server, in_tmux: bool, ae_owned: bool) -> Caller {
    Caller {
        in_tmux,
        ae_owned,
        server,
    }
}

